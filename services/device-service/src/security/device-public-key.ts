import { createHash, createPublicKey, verify, type KeyObject } from 'node:crypto';

/**
 * DER prefix of an Ed25519 SubjectPublicKeyInfo (RFC 8410): SEQUENCE { SEQUENCE { OID 1.3.101.112 },
 * BIT STRING (0 unused bits) }. The 32-byte raw public key follows.
 */
const ED25519_SPKI_PREFIX = Buffer.from('302a300506032b6570032100', 'hex');
const ED25519_SPKI_LENGTH = ED25519_SPKI_PREFIX.length + 32;
const ED25519_SIGNATURE_LENGTH = 64;

/** An Ed25519 SPKI is always 44 DER bytes, i.e. exactly one 60-character base64 line. */
const SPKI_PEM_PATTERN =
  /^-----BEGIN PUBLIC KEY-----\n([A-Za-z0-9+/]{59}=)\n-----END PUBLIC KEY-----\n?$/;
const BASE64URL_PATTERN = /^[A-Za-z0-9_-]+$/;

export const DEVICE_KEY_FINGERPRINT_PATTERN = /^sha256:[0-9a-f]{64}$/;

export class DevicePublicKeyError extends Error {
  constructor() {
    super('Invalid device public key');
    this.name = 'DevicePublicKeyError';
  }
}

export interface CanonicalDevicePublicKey {
  readonly algorithm: 'Ed25519';
  /** PEM regenerated by the server from the accepted DER; never the caller's text. */
  readonly publicKeyPem: string;
  readonly fingerprint: string;
}

export function fingerprintSpkiDer(der: Buffer): string {
  return `sha256:${createHash('sha256').update(der).digest('hex')}`;
}

/**
 * Accepts only an Ed25519 public key encoded as a single-line SPKI PEM. The textual format is
 * validated before any parser runs because `createPublicKey` also accepts private keys and
 * certificates (deriving their public part), which must never be stored as device identity.
 */
export function parseDevicePublicKey(input: unknown): CanonicalDevicePublicKey {
  if (typeof input !== 'string' || input.length > 4096) throw new DevicePublicKeyError();
  const match = SPKI_PEM_PATTERN.exec(input);
  const encoded = match?.[1];
  if (!encoded) throw new DevicePublicKeyError();

  const der = Buffer.from(encoded, 'base64');
  if (
    der.toString('base64') !== encoded ||
    der.length !== ED25519_SPKI_LENGTH ||
    !der.subarray(0, ED25519_SPKI_PREFIX.length).equals(ED25519_SPKI_PREFIX)
  ) {
    throw new DevicePublicKeyError();
  }

  let key: KeyObject;
  try {
    key = createPublicKey({ key: der, format: 'der', type: 'spki' });
  } catch {
    throw new DevicePublicKeyError();
  }
  if (key.type !== 'public' || key.asymmetricKeyType !== 'ed25519') {
    throw new DevicePublicKeyError();
  }
  const exported = key.export({ format: 'der', type: 'spki' });
  if (!exported.equals(der)) throw new DevicePublicKeyError();

  return Object.freeze({
    algorithm: 'Ed25519',
    publicKeyPem: key.export({ format: 'pem', type: 'spki' }).toString(),
    fingerprint: fingerprintSpkiDer(exported),
  });
}

/** Verifies an Ed25519 signature encoded as canonical unpadded base64url. Never throws. */
export function verifyDeviceSignature(
  publicKeyPem: string,
  message: Buffer,
  signatureBase64Url: string,
): boolean {
  if (!BASE64URL_PATTERN.test(signatureBase64Url)) return false;
  const signature = Buffer.from(signatureBase64Url, 'base64url');
  if (
    signature.length !== ED25519_SIGNATURE_LENGTH ||
    signature.toString('base64url') !== signatureBase64Url
  ) {
    return false;
  }
  try {
    const { publicKeyPem: canonical } = parseDevicePublicKey(publicKeyPem);
    return verify(null, message, createPublicKey(canonical), signature);
  } catch {
    return false;
  }
}
